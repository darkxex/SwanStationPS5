"""
  python3 tools/make_sjis_table.py      (writes src/ui/sjis_table.h)

The table has one row per lead byte (0x81-0x9F, 0xE0-0xEF) and 188 columns (trail bytes 0x40-0xFB);
0 means the code has no character.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "ui" / "sjis_table.h"
LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xF0))

rows = []
for lead in LEADS:
    row = []
    for trail in range(0x40, 0xFC):
        cp = 0
        if trail != 0x7F:
            try:
                s = bytes([lead, trail]).decode("cp932")
                if len(s) == 1:
                    cp = ord(s)
            except UnicodeDecodeError:
                pass
        row.append(cp)
    rows.append(row)

half = []
for b in range(0xA1, 0xE0):
    half.append(ord(__import__("unicodedata").normalize("NFKC", chr(0xFF61 + b - 0xA1)))
               if len(__import__("unicodedata").normalize("NFKC", chr(0xFF61 + b - 0xA1))) == 1 else 0x30FB)
half[0xDE - 0xA1] = 0x309B
half[0xDF - 0xA1] = 0x309C

with OUT.open("w", encoding="utf-8", newline="\n") as f:
    f.write("/* Generated by tools/make_sjis_table.py: do not edit. */\n")
    f.write("#ifndef SwanStationPS5_SJIS_TABLE_H\n#define SwanStationPS5_SJIS_TABLE_H\n\n")
    f.write("#include <stdint.h>\n\n")
    f.write("#define SJIS_ROWS %d\n#define SJIS_COLS 188\n\n" % len(LEADS))
    f.write("/* lead byte -> row, or -1 */\n")
    f.write("static inline int sjis_row(unsigned lead)\n{\n")
    f.write("    if (lead >= 0x81 && lead <= 0x9f)\n        return (int)lead - 0x81;\n")
    f.write("    if (lead >= 0xe0 && lead <= 0xef)\n        return (int)lead - 0xe0 + 31;\n    return -1;\n}\n\n")
    f.write("static const uint16_t sjis_to_ucs[SJIS_ROWS][SJIS_COLS] = {\n")
    for row in rows:
        f.write("    {" + ",".join("0x%x" % c for c in row) + "},\n")
    f.write("};\n\n/* single bytes 0xA1-0xDF: the half-width katakana, as full-width ones */\n")
    f.write("static const uint16_t sjis_half_to_ucs[63] = {" + ",".join("0x%x" % c for c in half) + "};\n\n#endif\n")
print("wrote", OUT, OUT.stat().st_size // 1024, "KB")
